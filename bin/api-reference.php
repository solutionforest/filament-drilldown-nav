#!/usr/bin/env php
<?php

/**
 * Prints docs/api-reference.md: the public API (every public method that is not marked @internal)
 * generated from the code, so the reference cannot drift. Update the file with:
 *
 *     php bin/api-reference.php > docs/api-reference.md
 *
 * A test (tests/DocsTest.php) fails when the committed file differs from this output.
 */

use SolutionForest\DrilldownNav\ChildDisplay;
use SolutionForest\DrilldownNav\Contracts\HasDrilldownRecordMenu;
use SolutionForest\DrilldownNav\DrilldownNavHook;
use SolutionForest\DrilldownNav\DrilldownNavPlugin;
use SolutionForest\DrilldownNav\Tree\NavItem;

require __DIR__.'/../vendor/autoload.php';

function summary(string|false $doc): string
{
    if ($doc === false) {
        return '';
    }

    $lines = [];
    foreach (preg_split('/\R/', $doc) ?: [] as $line) {
        $line = trim(preg_replace('#^\s*(/\*\*|\*/|\*)\s?#', '', $line) ?? '');
        $line = trim(preg_replace('#\s*\*/$#', '', $line) ?? '');
        if ($line === '' && $lines !== []) {
            break;
        }
        if (str_starts_with($line, '@')) {
            break;
        }
        if ($line !== '') {
            $lines[] = $line;
        }
    }

    $text = trim(implode(' ', $lines));

    return str_replace('|', '\\|', $text);
}

function typeName(?ReflectionType $type): string
{
    if ($type === null) {
        return 'mixed';
    }

    $name = (string) $type;
    $name = preg_replace_callback('/[\\\\\w]+/', fn (array $m): string => str_contains($m[0], '\\') ? substr(strrchr($m[0], '\\'), 1) : $m[0], $name) ?? $name;

    return str_replace('|', '\\|', $name);
}

function signature(ReflectionMethod $method): string
{
    $params = array_map(function (ReflectionParameter $p): string {
        $text = typeName($p->getType()).' $'.$p->getName();
        if ($p->isVariadic()) {
            $text = typeName($p->getType()).' ...$'.$p->getName();
        } elseif ($p->isDefaultValueAvailable()) {
            $text .= ' = '.str_replace(["\n", '  '], ' ', strtolower(var_export($p->getDefaultValue(), true)));
        }

        return $text;
    }, $method->getParameters());

    $return = $method->hasReturnType() ? ': '.typeName($method->getReturnType()) : '';

    return ($method->isStatic() ? 'static ' : '').$method->getName().'('.implode(', ', $params).')'.$return;
}

/** @return array<int, ReflectionMethod> */
function publicMethods(string $class): array
{
    $methods = array_filter(
        (new ReflectionClass($class))->getMethods(ReflectionMethod::IS_PUBLIC),
        fn (ReflectionMethod $m): bool => $m->getDeclaringClass()->getName() === $class
            && ! $m->isConstructor()
            && ! ($class === DrilldownNavPlugin::class && in_array($m->getName(), ['boot', 'register', 'getId'], true)) // Filament's plugin contract
            && ! str_contains((string) $m->getDocComment(), '@internal'),
    );

    usort($methods, fn (ReflectionMethod $a, ReflectionMethod $b): int => [(int) ! $a->isStatic(), $a->getName()] <=> [(int) ! $b->isStatic(), $b->getName()]);

    return array_values($methods);
}

$out = [];
$out[] = '# API reference';
$out[] = '';
$out[] = '<!-- Generated by `php bin/api-reference.php > docs/api-reference.md`. Do not edit by hand: a test fails when it is out of date. -->';
$out[] = '';
$out[] = 'The **public API**: every public method that is not marked `@internal`. Anything else may change in any release (see [API stability](api-stability.md)). Fluent methods return the object, so they chain.';
$out[] = '';

foreach ([
    DrilldownNavPlugin::class => ['Plugin', 'Registered on a panel with `->plugin(DrilldownNavPlugin::make()->…)`.'],
    NavItem::class => ['Menu items', 'Built with `NavItem::make()` and friends; returned from `->items(fn () => [...])`.'],
] as $class => [$title, $intro]) {
    $out[] = '## '.$title.' (`'.substr(strrchr($class, '\\'), 1).'`)';
    $out[] = '';
    $out[] = $intro;
    $out[] = '';
    $out[] = '| Method | What it does |';
    $out[] = '|---|---|';
    foreach (publicMethods($class) as $method) {
        $out[] = '| `'.signature($method).'` | '.(summary($method->getDocComment()) ?: '—').' |';
    }
    $out[] = '';
}

$out[] = '## Record menus declared on the resource (`HasDrilldownRecordMenu`)';
$out[] = '';
$out[] = 'Implement this interface on a Filament Resource to declare the menu shown inside one of its records, next to the resource itself. `NavItem::resource(YourResource::class)` then uses it with no extra config.';
$out[] = '';
$out[] = '| Method | What it does |';
$out[] = '|---|---|';
foreach ((new ReflectionClass(HasDrilldownRecordMenu::class))->getMethods() as $method) {
    $out[] = '| `'.signature($method).'` | The items of the menu shown inside this record. |';
}
$out[] = '';

$out[] = '## Display mode (`ChildDisplay`)';
$out[] = '';
$out[] = '| Case | Meaning |';
$out[] = '|---|---|';
foreach (ChildDisplay::cases() as $case) {
    $doc = (new ReflectionEnumBackedCase(ChildDisplay::class, $case->name))->getDocComment();
    $out[] = '| `ChildDisplay::'.$case->name.'` | '.(summary($doc) ?: '—').' |';
}
$out[] = '';

$out[] = '## Render hooks (`DrilldownNavHook`)';
$out[] = '';
$out[] = 'See [Render hooks](render-hooks.md). Every hook is scoped to the id of the panel being rendered.';
$out[] = '';
$out[] = '| Constant | Where it renders |';
$out[] = '|---|---|';
foreach ((new ReflectionClass(DrilldownNavHook::class))->getReflectionConstants() as $constant) {
    $out[] = '| `DrilldownNavHook::'.$constant->getName().'` | '.(summary($constant->getDocComment()) ?: '—').' |';
}
$out[] = '';

echo implode("\n", $out);
